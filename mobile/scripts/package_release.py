"""Package the existing desktop gallery and Android WebView site for private release."""
import hashlib, json, platform, subprocess, zipfile
from pathlib import Path
from importlib.metadata import version as package_version
from bs4 import BeautifulSoup
from release_input import source

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'mobile/build/site'

def desktop():
    raw,_=source(ROOT)
    soup=BeautifulSoup(raw.decode('utf-8'),'html.parser')
    mapping=json.loads((ROOT/'mobile/build/image-provenance.json').read_text(encoding='utf-8'))
    for im in soup.select('td.pictures img[src]'):
        relative=im['src']
        entry=mapping.get(relative)
        if not entry: raise ValueError('Missing display mapping: '+relative)
        im['data-original']=relative
        im['src']=entry['thumb']
        im['data-detail']=entry['src']
        im['loading']='lazy'
        if entry['processing']['status']=='crop-reviewed':
            figure=im.find_parent('figure')
            if figure:
                caption=figure.find('figcaption')
                if caption is None:
                    caption=soup.new_tag('figcaption');figure.append(caption)
                for label in ('裁去冗余画布','原背景保留'):
                    if label not in caption.get_text():caption.append(' · '+label)
        if entry['processing']['status']=='background-removed-reviewed':
            figure=im.find_parent('figure')
            if figure:
                caption=figure.find('figcaption')
                if caption is None:
                    caption=soup.new_tag('figcaption');figure.append(caption)
                if '背景已处理' not in caption.get_text():
                    caption.append(' · 背景已处理')
                if max(entry['processing']['sourceSize']) < 768 and '低清参考' not in caption.get_text():
                    caption.append(' · 低清参考')
    for script in soup.find_all('script'):
        if script.string:
            script.string=script.string.replace('viewerImage\').src=im.src','viewerImage\').src=im.dataset.detail||im.src')
    # Desktop CSS is generated by the existing builder; preserve its layout.
    style=ROOT/'assets/site.css'
    if style.exists():
        (OUT/'assets').mkdir(exist_ok=True)
        (OUT/'assets/site.css').write_bytes(style.read_bytes())
    (OUT/'desktop.html').write_text(str(soup),encoding='utf-8')
    local=BeautifulSoup(str(soup),'html.parser')
    for im in local.select('td.pictures img[src]'):
        im['src']='mobile/build/site/'+im['src']
        im['data-detail']='mobile/build/site/'+im['data-detail']
    (ROOT/'index.html').write_text(str(local),encoding='utf-8')

def package():
    desktop()
    version=json.loads((ROOT/'mobile/version.json').read_text())['name']
    archive=ROOT/'mobile/build'/('world-medals-html-'+version+'.zip')
    with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
        for path in sorted(OUT.rglob('*')):
            if path.is_file() and path.name!='desktop-template.html':z.write(path,path.relative_to(OUT).as_posix())
    apk=ROOT/'mobile/build'/('world-medals-'+version+'.apk')
    commit=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip()
    metadata={'version':version,'commit':commit,'python':platform.python_version(),
              'platform':platform.platform(),'Pillow':package_version('Pillow'),'beautifulsoup4':package_version('beautifulsoup4'),
              'androidPlatform':36,'androidBuildTools':'36.1.0 or 36.0.0 selected by build_apk.py','imageAlgorithm':'reviewed edge-connected neutral-light backgrounds 242/12 or near-black backgrounds using per-source maximum/chroma rules; optional reviewed keepPolygons; alpha/white margins; margin 3.5%; WebP 384/1200 q86/q90 method4; no model masks in release',
              'limitations':['Opaque backgrounds and uncertain identities require manual review.',
                              'Device installation is not verified unless separately reported.']}
    summary=ROOT/'mobile/build/background-continuation/summary.json'
    if summary.exists():metadata['backgroundReview']=json.loads(summary.read_text(encoding='utf-8'))
    from background_trim import load_rules
    rules = load_rules(ROOT)
    approved = [rule for rule in rules.values() if rule.get('approved') is True]
    metadata['approvedBackgroundRules'] = sum(rule.get('kind')!='crop-only' for rule in approved)
    metadata['reviewedCropRules'] = sum(rule.get('kind')=='crop-only' for rule in approved)
    metadata['reviewedAlphaRunRules'] = sum(rule.get('kind') == 'reviewed-runs' for rule in approved)
    metadata['imageAlgorithm'] += '; reviewed-runs retain frozen per-source alpha coordinates and original RGB'
    metadata['imageAlgorithm'] += '; crop-only retains the photographic background inside reviewed bounds and is counted separately'
    build_info=ROOT/'mobile/build/apk-build-info.json'
    if build_info.exists():
        info=json.loads(build_info.read_text(encoding='utf-8'))
        if info.get('artifact')==apk.name and info.get('version',{}).get('name')==version:
            metadata['apkBuild']=info
    if 'apkBuild' not in metadata:
        metadata['limitations'].append('APK source commit was not recorded by this build.')
    (ROOT/'mobile/build/release-info.json').write_text(json.dumps(metadata,ensure_ascii=False,indent=2),encoding='utf-8')
    lines=[]
    for path in (archive,apk):
        digest=hashlib.sha256()
        with path.open('rb') as f:
            for block in iter(lambda:f.read(1024*1024),b''):digest.update(block)
        lines.append(digest.hexdigest()+'  '+path.name)
    (ROOT/'mobile/build/SHA256SUMS.txt').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(json.dumps({'html':archive.name,'apk':apk.name,'commit':commit}))

if __name__=='__main__':package()
